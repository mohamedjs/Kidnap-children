export type Key = keyof typeof ar;
const dicts: Record<Locale, Dict> = { ar, en };

function initial(): Locale {
  try {
    return localStorage.getItem(KEY) === "en" ? "en" : "ar";
  } catch {
    return "ar";
  }
}

export const locale = ref<Locale>(initial());

function apply() {
  document.documentElement.lang = locale.value;
  document.documentElement.dir = locale.value === "ar" ? "rtl" : "ltr";
}
apply();

export function toggleLocale() {
  locale.value = locale.value === "ar" ? "en" : "ar";
  apply();
  try {
    localStorage.setItem(KEY, locale.value);
  } catch {
    /* ignore */
  }
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = dicts[locale.value][key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function fmtDate(iso: string | null | undefined): string {
  if (!iso) return "";
  return new Date(iso).toLocaleDateString(locale.value === "ar" ? "ar-EG" : "en-GB", {
    day: "numeric", month: "long", year: "numeric",
  });
}

export function timeAgo(iso: string): string {
  const rtf = new Intl.RelativeTimeFormat(locale.value === "ar" ? "ar-EG" : "en", { numeric: "auto" });
  const diff = (new Date(iso).getTime() - Date.now()) / 1000;
  const steps: [number, Intl.RelativeTimeFormatUnit][] = [[60, "second"], [60, "minute"], [24, "hour"], [30, "day"], [12, "month"]];
  let v = diff;
  for (const [n, unit] of steps) {
    if (Math.abs(v) < n) return rtf.format(Math.round(v), unit);
    v /= n;
  }
  return rtf.format(Math.round(v), "year");
}
